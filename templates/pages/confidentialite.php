    <h1>Politique de confidentialité</h1>

    <p>Cette page explique quelles données sont enregistrées quand tu utilises Analyste cyber, et pourquoi.</p>

    <h2>Les données enregistrées</h2>
    <ul>
        <li>ton pseudo et ton adresse e-mail, donnés à l'inscription</li>
        <li>ton mot de passe, enregistré seulement sous forme chiffrée (hachage) : personne ne peut le lire</li>
        <li>tes parties : date, durée, score, réponses envoyées et indices demandés</li>
    </ul>
    <p>Aucune autre donnée n'est demandée (pas de nom, pas d'adresse, pas de téléphone).</p>

    <h2>Pourquoi ces données</h2>
    <ul>
        <li>le pseudo et l'e-mail servent à créer ton compte et à te connecter</li>
        <li>les parties servent à calculer ton score, à afficher le classement et ton historique</li>
        <li>les réponses et les indices servent à l'administrateur pour voir où les joueurs bloquent et améliorer le jeu</li>
    </ul>
    <p>Ces données sont enregistrées parce que tu acceptes cette politique en créant ton compte.</p>

    <h2>Qui peut voir tes données</h2>
    <ul>
        <li>les autres joueurs voient seulement ton pseudo et ton score dans le classement</li>
        <li>l'administrateur du site voit ton pseudo, ton e-mail et tes parties</li>
        <li>tes données ne sont ni vendues ni partagées</li>
    </ul>
    <p>
        Le mentor IA (Mistral AI) reçoit seulement la question de la salle :
        jamais ton pseudo, ton e-mail ou tes réponses.
    </p>

    <h2>Où sont stockées tes données</h2>
    <p>
        Chez les hébergeurs du site (Heroku, JawsDB et MongoDB Atlas). Certains serveurs sont situés
        aux Etats-Unis.
    </p>

    <h2>Combien de temps</h2>
    <p>Tant que ton compte existe. Si ton compte est supprimé, toutes tes parties sont supprimées avec lui.</p>

    <h2>Cookies</h2>
    <p>
        Le site utilise un seul cookie, le cookie de session, qui sert à rester connecté.
        Il est supprimé quand tu fermes ton navigateur ou quand tu te déconnectes.
        Il n'y a pas de cookie de publicité ni de statistiques.
    </p>

    <h2>Tes droits</h2>
    <p>
        Tu peux demander à voir, corriger ou supprimer tes données en écrivant à
        <a href="mailto:mathieu.palle@outlook.fr">mathieu.palle@outlook.fr</a>.
        Si tu n'as pas de réponse, tu peux contacter la CNIL sur <a href="https://www.cnil.fr">cnil.fr</a>.
    </p>
